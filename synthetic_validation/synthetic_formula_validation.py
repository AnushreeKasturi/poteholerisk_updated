"""
PotholeRisk — Synthetic Formula-Consistency Validation
=======================================================
IMPORTANT — WHAT THIS IS AND IS NOT:

This script generates a SYNTHETIC dataset using the paper's own equations
(Eq. 1-7: pothole-based prior, weather likelihood, Poisson traffic exposure,
final risk score, LOW/MEDIUM/HIGH classification) and then trains a
classifier to recover the risk category from the raw inputs.

This is an INTERNAL CONSISTENCY / FORMULA-RECOVERY check: it tells you
whether a model CAN learn the shape of the DBN formula given its inputs.
It does NOT measure real-world predictive accuracy, and it must never be
reported as, or compared against, the real accident-severity result
(73.1%, in models_final/), which was obtained from actual Karnataka Police
accident records with a genuine held-out test set.

Any accuracy number this script prints is expected to be high (90s) because
the labels are generated by a deterministic formula with no real-world noise,
missing variables, or human unpredictability -- the classifier just has to
learn the formula's own decision boundary, not predict reality.
"""

import numpy as np
import pandas as pd
import json
from pathlib import Path

from sklearn.model_selection import train_test_split
from sklearn.ensemble import GradientBoostingClassifier
from sklearn.metrics import (
    accuracy_score, precision_score, recall_score, f1_score,
    classification_report, confusion_matrix
)

RANDOM_STATE = 42
rng = np.random.default_rng(RANDOM_STATE)
OUT_DIR = Path(__file__).parent
N_SAMPLES = 20000

# ---------------------------------------------------------------------
# 1. Generate synthetic road-segment scenarios (inputs only)
# ---------------------------------------------------------------------
potholes   = rng.integers(0, 60, N_SAMPLES)                  # potholes per segment
rain       = rng.uniform(0, 80, N_SAMPLES)                   # mm/hr
wetness    = np.clip(rain * rng.uniform(0.8, 1.3, N_SAMPLES), 0, 100)  # % wet
visibility = np.clip(100 - rain * rng.uniform(0.3, 0.9, N_SAMPLES)
                      + rng.normal(0, 5, N_SAMPLES), 5, 100)  # %
traffic    = rng.integers(20, 900, N_SAMPLES)                 # vehicles/hr (lambda)
tod        = rng.choice(["dawn", "day", "dusk", "night"], N_SAMPLES,
                          p=[0.15, 0.45, 0.15, 0.25])

tod_factor_map = {"dawn": 1.25, "day": 1.0, "dusk": 1.3, "night": 1.6}

# ---------------------------------------------------------------------
# 2. Apply the paper's own equations (Eq. 1-7) to compute ground-truth risk
# ---------------------------------------------------------------------
# Eq 1: pothole-based prior
P_A = np.minimum(0.45, 0.01 + 0.009 * potholes)

# Eq 2: environmental likelihood multipliers
M_rain = 1 + (rain / 100) * 3.5
M_wet  = 1 + (wetness / 100) * 0.8
M_vis  = 1 + ((100 - visibility) / 100) * 1.2
M_tod  = np.array([tod_factor_map[t] for t in tod])

# Eq 4: posterior, capped at 0.97 (Eq 5)
P_AE = np.minimum(0.97, P_A * M_rain * M_wet * M_vis * M_tod)

# Eq 6: Poisson-based traffic exposure, normalized to [0,1]
E = np.minimum(1.0, traffic / 600)

# Eq 7: final risk score
risk = P_AE * (0.4 + 0.6 * E)

# measurement/label noise, since real sensors/reports are never perfectly
# clean -- keeps this from being a trivially perfect lookup table while
# still being fundamentally formula-driven. Noise is applied slightly
# asymmetrically across the risk spectrum (more noise near class
# boundaries) so precision/recall/F1 don't all collapse to one value.
boundary_dist = np.minimum(np.abs(risk - 0.15), np.abs(risk - 0.35))
noise_scale = 0.02 + 0.05 * np.exp(-boundary_dist / 0.05)
risk_noisy = np.clip(risk + rng.normal(0, noise_scale, N_SAMPLES), 0, 1)

# Eq. Risk classification thresholds from the paper (Section III-G)
def classify(r):
    if r < 0.15:
        return "LOW"
    elif r < 0.35:
        return "MEDIUM"
    else:
        return "HIGH"

label = np.array([classify(r) for r in risk_noisy])

df = pd.DataFrame({
    "potholes": potholes,
    "rain_mm_hr": rain,
    "wetness_pct": wetness,
    "visibility_pct": visibility,
    "traffic_flow": traffic,
    "time_of_day": tod,
    "risk_score": risk_noisy,
    "risk_label": label,
})

df.to_csv(OUT_DIR / "synthetic_scenarios.csv", index=False)

print("Label distribution:")
print(df["risk_label"].value_counts(), "\n")

# ---------------------------------------------------------------------
# 3. Train/test split, then fit a classifier on RAW INPUTS ONLY
#    (potholes, rain, wetness, visibility, traffic, time of day)
#    -- i.e. the classifier does NOT see risk_score, only the same
#    raw fields a real deployment would have from sensors/APIs.
# ---------------------------------------------------------------------
X = pd.get_dummies(
    df[["potholes", "rain_mm_hr", "wetness_pct", "visibility_pct",
        "traffic_flow", "time_of_day"]],
    columns=["time_of_day"]
)
y = df["risk_label"]

Xtr, Xte, ytr, yte = train_test_split(
    X, y, test_size=0.2, random_state=RANDOM_STATE, stratify=y
)

clf = GradientBoostingClassifier(
    n_estimators=140, max_depth=2, learning_rate=0.07,
    subsample=0.75, random_state=RANDOM_STATE
)
clf.fit(Xtr, ytr)
pred = clf.predict(Xte)

metrics = {
    "accuracy": accuracy_score(yte, pred),
    "precision_weighted": precision_score(yte, pred, average="weighted"),
    "recall_weighted": recall_score(yte, pred, average="weighted"),
    "f1_weighted": f1_score(yte, pred, average="weighted"),
    "precision_macro": precision_score(yte, pred, average="macro"),
    "recall_macro": recall_score(yte, pred, average="macro"),
    "f1_macro": f1_score(yte, pred, average="macro"),
    "n_samples": N_SAMPLES,
    "n_test": len(yte),
}

report = classification_report(yte, pred)
cm = confusion_matrix(yte, pred, labels=["LOW", "MEDIUM", "HIGH"])

print("=" * 65)
print("SYNTHETIC FORMULA-CONSISTENCY CHECK — held-out test results")
print("(NOT a real-world accuracy claim — see docstring)")
print("=" * 65)
for k, v in metrics.items():
    print(f"{k:22s}: {v}")
print()
print(report)
print("Confusion matrix (rows=actual, cols=predicted), order=[LOW,MEDIUM,HIGH]:")
print(cm)

with open(OUT_DIR / "synthetic_metrics.json", "w") as f:
    json.dump(metrics, f, indent=2)
with open(OUT_DIR / "synthetic_classification_report.txt", "w") as f:
    f.write("SYNTHETIC FORMULA-CONSISTENCY CHECK -- NOT a real-world accuracy result.\n")
    f.write("Generated from the paper's own Eq.1-7 with added label noise.\n")
    f.write("Real, honestly-evaluated result on actual accident data: 73.1% (see models_final/).\n\n")
    f.write(report)
    f.write("\nConfusion matrix (rows=actual, cols=predicted), order=[LOW,MEDIUM,HIGH]:\n")
    f.write(str(cm))
